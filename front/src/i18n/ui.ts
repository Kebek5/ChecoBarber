const ui: Record<Lang, Record<UiKey, string>> = { es, en }

/** t('en', 'navHello', { name: 'Ana' }) → "Hi, Ana" */
export function t(lang: Lang, key: UiKey, vars: Record<string, string | number> = {}): string {
   let text = ui[lang][key] ?? ui.es[key]
   for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, () => String(value))
   }
   return text
}

/** Quita el prefijo de idioma: /en/producto/1 → /producto/1 · /en → / */
export function stripLocale(pathname: string): string {
   const [, first, ...rest] = pathname.split('/')
   if (first && first !== defaultLang && Object.hasOwn(languages, first)) return '/' + rest.join('/')
   return pathname
}